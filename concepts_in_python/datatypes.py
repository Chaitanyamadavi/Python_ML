#tuples- they are same as lists, but we use (), inside print statements. Instead of []

print((1,2,3,4,5))

#sets- they are also used for storing a set of data, but we use {} inside print statements

print({1,2,3,4,5})

#dictionary- we use this to make key value pairs

print({"Name":"napo", "age": 28, "gender": "male"})